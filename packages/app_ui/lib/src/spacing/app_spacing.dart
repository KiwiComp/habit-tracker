/// Spacing values following Material's 4dp grid.
///
/// See: https://m3.material.io/foundations/layout/understanding-layout/spacing
class AppSpacing {
  /// Creates an [AppSpacing].
  const AppSpacing();

  /// 4.
  double get xs => 4;

  /// 8.
  double get sm => 8;

  /// 16.
  double get md => 16;

  /// 24.
  double get lg => 24;

  /// 32.
  double get xl => 32;

  /// 48.
  double get xxl => 48;

  /// 64.
  double get xxxl => 64;
}
