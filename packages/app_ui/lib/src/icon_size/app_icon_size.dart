/// Icon sizes following Material's standard icon size scale.
///
/// See: https://m2.material.io/design/iconography/system-icons.html#sizing
class AppIconSize {
  /// Creates an [AppIconSize].
  const AppIconSize();

  /// 12. Very small icon size.
  double get xs => 12;

  /// 18. Dense icon size.
  double get sm => 18;

  /// 24. The default icon size.
  double get md => 24;

  /// 36. Large icon size.
  double get lg => 36;

  /// 48. Extra large icon size.
  double get xl => 48;
}
